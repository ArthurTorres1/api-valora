-- Criação da tabela de Usuário (Sem Endereço)
CREATE TABLE T_VLR_USUARIO (
        ID_USUARIO NUMBER(19) GENERATED ALWAYS AS IDENTITY,
        NM_USUARIO VARCHAR2(100) NOT NULL,
        DS_EMAIL VARCHAR2(100) NOT NULL,
        DS_SENHA_HASH VARCHAR2(255) NOT NULL,
        NR_CPF VARCHAR2(11) NOT NULL,
        DT_NASCIMENTO DATE NOT NULL,
        DT_CRIACAO DATE DEFAULT SYSDATE NOT NULL,
        CONSTRAINT PK_T_VLR_USUARIO PRIMARY KEY (ID_USUARIO),
        CONSTRAINT UK_T_VLR_USUARIO_EMAIL UNIQUE (DS_EMAIL),
        CONSTRAINT UK_T_VLR_USUARIO_CPF UNIQUE (NR_CPF),
        CONSTRAINT CK_T_VLR_USUARIO_EMAIL CHECK (REGEXP_LIKE(DS_EMAIL, '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$')),
        CONSTRAINT CK_T_VLR_USUARIO_CPF CHECK (REGEXP_LIKE(NR_CPF, '^[0-9]{11}$'))
);

-- Criação da tabela de Conta
CREATE TABLE T_VLR_CONTA (
        ID_CONTA NUMBER(19) GENERATED ALWAYS AS IDENTITY,
        ID_USUARIO NUMBER(19) NOT NULL,
        NM_CONTA VARCHAR2(100) NOT NULL,
        VL_SALDO NUMBER(19, 2) DEFAULT 0 NOT NULL,
        DT_CRIACAO DATE DEFAULT SYSDATE NOT NULL,
        CONSTRAINT PK_T_VLR_CONTA PRIMARY KEY (ID_CONTA),
        CONSTRAINT FK_T_VLR_CONTA_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES T_VLR_USUARIO (ID_USUARIO)
);

-- Criação da tabela de Categoria
CREATE TABLE T_VLR_CATEGORIA (
        ID_CATEGORIA NUMBER(19) GENERATED ALWAYS AS IDENTITY,
        ID_USUARIO NUMBER(19) NOT NULL,
        NM_CATEGORIA VARCHAR2(100) NOT NULL,
        DT_CRIACAO DATE DEFAULT SYSDATE NOT NULL,
        CONSTRAINT PK_T_VLR_CATEGORIA PRIMARY KEY (ID_CATEGORIA),
        CONSTRAINT FK_T_VLR_CATEG_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES T_VLR_USUARIO (ID_USUARIO)
);

-- Criação da tabela de Caixinha
CREATE TABLE T_VLR_CAIXINHA (
        ID_CAIXINHA NUMBER(19) GENERATED ALWAYS AS IDENTITY,
        ID_USUARIO NUMBER(19) NOT NULL,
        NM_CAIXINHA VARCHAR2(100) NOT NULL,
        VL_META NUMBER(19, 2),
        VL_ATUAL NUMBER(19, 2) DEFAULT 0 NOT NULL,
        DT_CRIACAO DATE DEFAULT SYSDATE NOT NULL,
        CONSTRAINT PK_T_VLR_CAIXINHA PRIMARY KEY (ID_CAIXINHA),
        CONSTRAINT FK_T_VLR_CAIX_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES T_VLR_USUARIO (ID_USUARIO)
);

-- Criação da tabela de Movimentação (Com Integração Belvo e Arco Exclusivo)
CREATE TABLE T_VLR_MOVIMENTACAO (
        ID_MOVIMENTACAO NUMBER(19) GENERATED ALWAYS AS IDENTITY,
        ID_CONTA NUMBER(19),
        ID_CAIXINHA NUMBER(19),
        ID_CATEGORIA NUMBER(19) NOT NULL,
        VL_MOVIMENTACAO NUMBER(19, 2) NOT NULL,
        TP_MOVIMENTACAO VARCHAR2(20) NOT NULL,
        DT_MOVIMENTACAO DATE NOT NULL,
        CD_BELVO_TRANSACAO VARCHAR2(100),
        FL_INSERIDA_MANUAL NUMBER(1) DEFAULT 1 NOT NULL, -- 1 para Sim, 0 para Não
        DT_CRIACAO DATE DEFAULT SYSDATE NOT NULL,
        CONSTRAINT PK_T_VLR_MOVIMENTACAO PRIMARY KEY (ID_MOVIMENTACAO),
        CONSTRAINT FK_T_VLR_MOV_CONTA FOREIGN KEY (ID_CONTA) REFERENCES T_VLR_CONTA (ID_CONTA),
        CONSTRAINT FK_T_VLR_MOV_CAIXINHA FOREIGN KEY (ID_CAIXINHA) REFERENCES T_VLR_CAIXINHA (ID_CAIXINHA),
        CONSTRAINT FK_T_VLR_MOV_CATEGORIA FOREIGN KEY (ID_CATEGORIA) REFERENCES T_VLR_CATEGORIA (ID_CATEGORIA),
-- Constraint do Arco Exclusivo: Pertence à Conta OU à Caixinha, nunca aos dois
CONSTRAINT CK_T_VLR_MOV_ARCO CHECK (
        (ID_CONTA IS NOT NULL AND ID_CAIXINHA IS NULL) OR
        (ID_CONTA IS NULL AND ID_CAIXINHA IS NOT NULL)
    )
);